/**
 * Единственная нормализация имён в проекте.
 *
 * В v1 регистронезависимость держалась на двух разных функциях: `lower()` в
 * SQL и `toLocaleLowerCase('ru')` в JS. Для символов, где они расходятся,
 * приложение считало имена разными, а база — одинаковыми, и вставка падала с
 * 21000 вместо внятной ошибки.
 *
 * Теперь ключ считает только TS, а база хранит готовый результат в
 * `people.name_key` / `users.username_key`. Разойтись им негде.
 *
 * Менять эту функцию задним числом нельзя без пересчёта обеих колонок —
 * старые ключи останутся в прежнем виде и перестанут совпадать с новыми.
 */
export function normalizeKey(value: string): string {
  return value.trim().replace(/\s+/g, ' ').toLocaleLowerCase('ru');
}
