/**
 * Разбор ошибок базы там, где реакция на них разная.
 *
 * Обычно нарушение уникальности — это одна понятная ошибка на весь запрос
 * («такое имя уже занято»), и разбирать её незачем. Но одна вставка может
 * нарушить два разных ограничения — скажем, занятое имя аккаунта и уже
 * привязанный Яндекс, — и тогда важно, какое именно.
 */

/**
 * Нарушено ли уникальное ограничение, в котором участвует эта колонка.
 *
 * Prisma говорит о виновнике по-разному: в `meta.target` — при работе через
 * собственный движок, а через driver adapter (наш случай, см. lib/prisma.ts) —
 * в `meta.driverAdapterError.cause.constraint.fields`, да ещё и вместе с
 * текстом ошибки от Postgres. Полагаться на конкретную форму значит завести
 * ветку, которая молча перестанет срабатывать при обновлении Prisma, — поэтому
 * имя колонки ищется по всему `meta`.
 *
 * Имена колонок в схеме не пересекаются как подстроки (`user_id` не встречается
 * внутри `provider_account_id` и наоборот), так что ложным совпадениям взяться
 * неоткуда.
 */
export function uniqueViolationOn(error: unknown, column: string): boolean {
  if (!error || typeof error !== 'object') return false;
  if ((error as { code?: string }).code !== 'P2002') return false;

  return JSON.stringify((error as { meta?: unknown }).meta ?? '').includes(column);
}
