-- ############################################################################
-- Ссылка-приглашение хранится открытым текстом, а не хешем.
--
-- Раньше в базе лежал sha256 токена — по образцу sessions, — и значение
-- ссылки было известно только тому браузеру, которому её показали в момент
-- выпуска. Это мешает ровно тому, ради чего ссылка нужна: организатор должен
-- увидеть её на экране клуба с телефона, с ноутбука, после перезагрузки —
-- с любого устройства, где он вошёл в клуб.
--
-- Цена этого решения мала: приглашение даёт роль участника и ничего больше,
-- участник почти ничего не может. Хешем нельзя было бы восстановить
-- значение, даже согласившись на риск, — из хеша исходную строку не достать.
--
-- Существующие приглашения (пока был хеш) восстановить нельзя технически,
-- поэтому строки просто уходят: ссылки живут максимум 7 дней и не несут
-- истории — организатору, если ссылка ещё нужна, придётся выпустить новую.
-- ############################################################################

DELETE FROM "club_invites";

DROP INDEX "club_invites_token_hash_key";

ALTER TABLE "club_invites" DROP COLUMN "token_hash";
ALTER TABLE "club_invites" ADD COLUMN "token" TEXT NOT NULL;

ALTER TABLE "club_invites"
  ADD CONSTRAINT club_invites_token_len CHECK (length(token) BETWEEN 16 AND 64);

CREATE UNIQUE INDEX "club_invites_token_key" ON "club_invites"("token");
