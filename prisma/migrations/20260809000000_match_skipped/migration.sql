-- Mexicano: пропущенный матч.
--
-- Следующий раунд мексикано — функция от таблицы, поэтому его не существует,
-- пока в текущем не сыграно всё. Одна четвёрка, которой сейчас не выйти на
-- корт, останавливает этим весь турнир: остальные доиграли, а составов
-- следующего раунда нет.
--
-- Отметка снимает ровно это. Раунд считается доигранным без пропущенного
-- матча, но сам матч никуда не девается: счёт в него вносят позже, и в таблицу
-- он попадает наравне с остальными. Отсюда и то, чего здесь нет, — удаления
-- матча: пропустить и отменить это разные вещи.
--
-- Метка времени, а не boolean, — по той же причине, что completed_at и
-- closed_at: «когда пропустили» стоит ровно столько же, сколько «пропущен ли».
-- ############################################################################

-- AlterTable
ALTER TABLE "matches" ADD COLUMN "skipped_at" TIMESTAMPTZ(6);

-- Пропущен — значит счёта нет. Внесённый счёт снимает отметку (setMatchScore в
-- src/lib/tournaments.ts), поэтому «пропущенный матч со счётом» — не состояние,
-- а противоречие, и база его не хранит.
ALTER TABLE "matches"
  ADD CONSTRAINT matches_skipped_unplayed CHECK (skipped_at IS NULL OR score_a IS NULL);
