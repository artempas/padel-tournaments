-- ############################################################################
-- Имя аккаунта при входе через провайдера выбирает человек.
--
-- Раньше именем становился логин у провайдера — то есть в турнирной таблице
-- человек появлялся под «artem08072002». Теперь между возвращением от
-- провайдера и созданием аккаунта есть разговор: «как вас называть».
--
-- Начатая регистрация живёт здесь, а не в куке, ровно по той же причине, что и
-- webauthn_challenges: в ней лежит идентификатор пользователя у провайдера,
-- то есть готовый пропуск в аккаунт. Подписать куку нечем — своего секрета у
-- приложения нет, — а строку в базе клиент выбрать не может: в куку уходит
-- только её непредсказуемый id.
--
-- Аккаунта до конца разговора не существует: бросил на полпути — и не осталось
-- ничего. Уборка протухших строк — там же, где для challenge (lib/auth.ts).
-- ############################################################################

-- CreateTable
CREATE TABLE "oauth_signups" (
    "id" UUID NOT NULL DEFAULT gen_random_uuid(),
    "provider" "oauth_provider" NOT NULL,
    "provider_account_id" TEXT NOT NULL,
    "login" TEXT,
    "email" TEXT,
    -- Куда человек шёл до того, как его отправили выбирать имя.
    "next" TEXT NOT NULL,
    "expires_at" TIMESTAMPTZ(6) NOT NULL,
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "oauth_signups_pkey" PRIMARY KEY ("id")
);

-- CreateIndex
CREATE INDEX "oauth_signups_expires_at_idx" ON "oauth_signups"("expires_at");
